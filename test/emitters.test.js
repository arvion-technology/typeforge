import test from "node:test";
import assert from "node:assert/strict";

import { buildIR } from "../src/ir.js";
import { emitTypeScript } from "../src/emit/typescript.js";
import { emitZod } from "../src/emit/zod.js";
import { emitPython } from "../src/emit/python.js";
import { emitGo } from "../src/emit/go.js";
import { sampleById } from "../src/samples.js";

const user = buildIR(sampleById("user-profile").schema);
const comments = buildIR(sampleById("comment-thread").schema);
const events = buildIR(sampleById("event-envelope").schema);

test("TypeScript emits interfaces, optional fields and enum unions", () => {
  const code = emitTypeScript(user);
  assert.match(code, /export interface UserProfile \{/);
  assert.match(code, /role: Role;/);
  assert.match(code, /displayName\?: string;/);
  assert.match(code, /tags\?: string\[\];/);
  assert.match(code, /metadata\?: \{ \[key: string\]: string \| undefined \};/);
  assert.match(code, /export interface Address \{/);
  assert.match(code, /export type Role = "owner" \| "admin" \| "member" \| "viewer";/);
});

test("TypeScript represents unions and nullable fields", () => {
  const code = emitTypeScript(events);
  assert.match(code, /payload: OrderCreated \| OrderPaid \| UserInvited;/);
  assert.match(code, /type: "order\.created" \| "order\.paid" \| "user\.invited";/);
  const nullable = emitTypeScript(comments);
  assert.match(nullable, /editedAt\?: string \| null;/);
});

test("Zod emits validators with constraints and refs", () => {
  const code = emitZod(user);
  assert.match(code, /import \{ z \} from "zod";/);
  assert.match(code, /export const RoleSchema = z\.enum\(\["owner", "admin", "member", "viewer"\]\);/);
  assert.match(code, /email: z\.string\(\)\.email\(\),/);
  assert.match(code, /members: z\.array\(UserSummarySchema\)\.optional\(\),/);
  assert.match(code, /country: z\.string\(\)\.min\(2\),/);
  assert.match(code, /postalCode: z\.string\(\)\.regex\(new RegExp\("\^\[0-9\]\{5\}\$"\)\)\.optional\(\),/);
  assert.match(code, /metadata: z\.record\(z\.string\(\)\)\.optional\(\),/);
  assert.match(code, /export type UserProfile = z\.infer<typeof UserProfileSchema>;/);
});

test("Zod uses z.lazy for a recursive schema", () => {
  const code = emitZod(comments);
  assert.match(code, /replies: z\.array\(z\.lazy\(\(\) => CommentSchema\)\)\.optional\(\),/);
  assert.match(code, /avatarUrl: z\.string\(\)\.url\(\)\.nullable\(\)\.optional\(\),/);
});

test("Zod represents unions as z.union of named schemas", () => {
  const code = emitZod(events);
  assert.match(code, /payload: z\.union\(\[OrderCreatedSchema, OrderPaidSchema, UserInvitedSchema\]\),/);
  assert.match(code, /attempt: z\.number\(\)\.int\(\)\.min\(1\)\.optional\(\),/);
});

test("Python emits dataclasses, enums and typed fields", () => {
  const code = emitPython(user);
  assert.match(code, /from __future__ import annotations/);
  assert.match(code, /from dataclasses import dataclass/);
  assert.match(code, /class Role\(str, Enum\):/);
  assert.match(code, /@dataclass\nclass UserProfile:/);
  assert.match(code, /last_seen_at: Optional\[datetime\] = None/);
  assert.match(code, /metadata: Optional\[Dict\[str, Any\]\] = None/);
  assert.match(code, /from datetime import datetime/);
  assert.match(code, /from typing import Any, Dict, List, Optional/);
});

test("Python places defaulted fields after required ones", () => {
  const code = emitPython(user);
  const userClass = code.slice(code.indexOf("class UserProfile:"));
  assert.ok(userClass.indexOf("id: str") < userClass.indexOf("display_name"));
  assert.ok(userClass.indexOf("email: str") < userClass.indexOf("marketing_opt_in"));
  assert.match(userClass, /marketing_opt_in: bool = False/);
});

test("Python handles recursive and union types with forward references", () => {
  const commentsCode = emitPython(comments);
  assert.match(commentsCode, /replies: Optional\[List\[Comment\]\] = None/);
  const eventsCode = emitPython(events);
  assert.match(eventsCode, /payload: Union\[OrderCreated, OrderPaid, UserInvited\]/);
  assert.match(eventsCode, /type: Literal\["order\.created", "order\.paid", "user\.invited"\]/);
  assert.match(eventsCode, /attempt: int = 1/);
});

test("Go emits structs, json tags and pointer optionals", () => {
  const code = emitGo(user);
  assert.match(code, /^\/\/ Code generated by TypeForge/m);
  assert.match(code, /package models/);
  assert.match(code, /type Role string/);
  assert.match(code, /RoleOwner Role = "owner"/);
  assert.match(code, /type UserProfile struct \{/);
  assert.match(code, /ID\s+string `json:"id"`/);
  assert.match(code, /DisplayName\s+\*string `json:"displayName,omitempty"`/);
  assert.match(code, /Address\s+Address `json:"address"`/);
  assert.match(code, /Metadata\s+map\[string\]any `json:"metadata,omitempty"`/);
});

test("Go emits recursion, unions and the json import", () => {
  const commentsCode = emitGo(comments);
  assert.match(commentsCode, /Replies\s+\[\]Comment `json:"replies,omitempty"`/);
  const eventsCode = emitGo(events);
  assert.match(eventsCode, /Payload\s+json\.RawMessage `json:"payload"`/);
  assert.match(eventsCode, /"encoding\/json"/);
});

test("every emitter ends with a newline and mentions the root type", () => {
  for (const emit of [emitTypeScript, emitZod, emitPython, emitGo]) {
    const code = emit(user);
    assert.ok(code.endsWith("\n"), emit.name);
    assert.match(code, /UserProfile/, emit.name);
    assert.ok(code.split("\n").length > 20, `${emit.name} produced ${code.split("\n").length} lines`);
  }
});
