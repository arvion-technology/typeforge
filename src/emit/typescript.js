// TypeScript emitter: one interface (or alias) per named schema.
import { KIND, orderedDefinitions } from "../ir.js";
import { pascal, propertyKey, lineComments } from "../format.js";

function needsParens(node) {
  return node && (node.kind === KIND.UNION || node.kind === KIND.INTERSECTION);
}

export function tsType(node) {
  if (!node) return "unknown";
  let base;
  switch (node.kind) {
    case KIND.REF:
      base = pascal(node.name);
      break;
    case KIND.STRING:
      base = "string";
      break;
    case KIND.INTEGER:
    case KIND.NUMBER:
      base = "number";
      break;
    case KIND.BOOLEAN:
      base = "boolean";
      break;
    case KIND.NULL:
      base = "null";
      break;
    case KIND.ANY:
      base = "unknown";
      break;
    case KIND.ENUM:
      base = node.values.map((value) => JSON.stringify(value)).join(" | ") || "never";
      break;
    case KIND.UNION:
      base = node.variants.map(tsType).join(" | ") || "never";
      break;
    case KIND.INTERSECTION:
      base = node.parts.map((part) => (needsParens(part) ? `(${tsType(part)})` : tsType(part))).join(" & ") || "unknown";
      break;
    case KIND.ARRAY: {
      const inner = tsType(node.items);
      base = `${needsParens(node.items) ? `(${inner})` : inner}[]`;
      break;
    }
    case KIND.OBJECT:
      base = objectLiteral(node);
      break;
    default:
      base = "unknown";
  }
  if (node.nullable && base !== "null" && base !== "unknown" && !base.endsWith("| null")) base = `${base} | null`;
  return base;
}

function objectLiteral(node) {
  if (!node.properties.length && !node.additional) return node.open ? "Record<string, unknown>" : "Record<string, never>";
  const fields = node.properties.map((property) =>
    `${propertyKey(property.name)}${property.required ? "" : "?"}: ${tsType(property.node)}`);
  if (node.additional) fields.push(`[key: string]: ${tsType(node.additional)} | undefined`);
  else if (node.open) fields.push("[key: string]: unknown");
  return `{ ${fields.join("; ")} }`;
}

function emitFields(node, indent = "  ") {
  const lines = [];
  for (const property of node.properties) {
    if (property.description) lines.push(...lineComments(property.description, indent.length));
    const optional = property.required ? "" : "?";
    lines.push(`${indent}${propertyKey(property.name)}${optional}: ${tsType(property.node)};`);
  }
  if (node.additional) lines.push(`${indent}[key: string]: unknown;`);
  return lines;
}

function emitDefinition(definition) {
  const { name, node } = definition;
  const lines = [];
  if (node.description) lines.push(...lineComments(node.description));
  if (node.kind === KIND.OBJECT) {
    lines.push(`export interface ${pascal(name)} {`);
    lines.push(...emitFields(node));
    lines.push("}");
  } else {
    lines.push(`export type ${pascal(name)} = ${tsType(node)};`);
  }
  return lines;
}

export function emitTypeScript(ir) {
  const lines = [
    `// Generated by TypeForge from ${ir.rootName}.`,
    "// Runtime validation is emitted separately for Zod; these are compile-time types only.",
    "",
  ];
  for (const definition of orderedDefinitions(ir)) {
    lines.push(...emitDefinition(definition), "");
  }

  const rootName = pascal(ir.rootName);
  const alreadyNamed = ir.root.kind === KIND.REF && pascal(ir.root.name) === rootName;
  if (!alreadyNamed) {
    if (ir.root.kind === KIND.OBJECT) {
      if (ir.root.description) lines.push(...lineComments(ir.root.description));
      lines.push(`export interface ${rootName} {`, ...emitFields(ir.root), "}");
    } else {
      lines.push(`export type ${rootName} = ${tsType(ir.root)};`);
    }
  }
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}
