// Zod emitter: runtime validators that mirror the TypeScript types.
import { KIND, orderedDefinitions } from "../ir.js";
import { pascal, propertyKey, lineComments } from "../format.js";

const FORMAT_CHAINS = {
  email: ".email()",
  uuid: ".uuid()",
  url: ".url()",
  uri: ".url()",
  "date-time": ".datetime({ offset: true })",
  ipv4: ".ip({ version: \"v4\" })",
  ipv6: ".ip({ version: \"v6\" })",
};

function literal(value) {
  if (typeof value === "string") return `z.literal(${JSON.stringify(value)})`;
  if (typeof value === "number" || typeof value === "boolean") return `z.literal(${String(value)})`;
  if (value === null) return "z.null()";
  return `z.literal(${JSON.stringify(value)})`;
}

function stringSchema(node) {
  const base = "z.string()";
  const chains = [];
  if (node.minLength !== undefined) chains.push(`.min(${node.minLength})`);
  if (node.maxLength !== undefined) chains.push(`.max(${node.maxLength})`);
  if (node.pattern) chains.push(`.regex(new RegExp(${JSON.stringify(node.pattern)}))`);
  if (node.format && FORMAT_CHAINS[node.format]) chains.push(FORMAT_CHAINS[node.format]);
  return base + chains.join("");
}

function numberSchema(node) {
  const chains = node.kind === KIND.INTEGER ? [".int()"] : [];
  if (node.minimum !== undefined) chains.push(`.min(${node.minimum})`);
  if (node.maximum !== undefined) chains.push(`.max(${node.maximum})`);
  if (node.multipleOf !== undefined) chains.push(`.multipleOf(${node.multipleOf})`);
  return "z.number()" + chains.join("");
}

function objectSchema(node, ref, indent) {
  // A properties-less object with additionalProperties is a map, and
  // z.record is both shorter and correctly typed; an index signature inside
  // z.object() is not valid TypeScript.
  if (!node.properties.length && node.additional) return `z.record(${zodFor(node.additional, ref, indent)})`;
  if (!node.properties.length && !node.open) return "z.object({})";
  const inner = node.properties.map((property) => {
    const optional = property.required ? "" : ".optional()";
    const rendered = zodFor(property.node, ref, indent + "  ");
    return `${indent}  ${propertyKey(property.name)}: ${rendered}${optional},`;
  });
  const lines = ["z.object({", ...inner, `${indent}})`];
  const suffix = node.additional ? `.catchall(${zodFor(node.additional, ref, indent)})` : node.open ? ".passthrough()" : node.closed ? ".strict()" : "";
  lines[lines.length - 1] += suffix;
  return lines.join("\n");
}

function zodFor(node, ref, indent = "") {
  if (!node) return "z.unknown()";
  let base;
  switch (node.kind) {
    case KIND.REF:
      base = ref(node);
      break;
    case KIND.STRING:
      base = stringSchema(node);
      break;
    case KIND.INTEGER:
    case KIND.NUMBER:
      base = numberSchema(node);
      break;
    case KIND.BOOLEAN:
      base = "z.boolean()";
      break;
    case KIND.NULL:
      base = "z.null()";
      break;
    case KIND.ANY:
      base = "z.unknown()";
      break;
    case KIND.ENUM: {
      const values = node.values;
      if (values.length && values.every((value) => typeof value === "string")) {
        base = `z.enum([${values.map((value) => JSON.stringify(value)).join(", ")}])`;
      } else if (values.length === 1) {
        base = literal(values[0]);
      } else {
        base = `z.union([${values.map(literal).join(", ")}])`;
      }
      break;
    }
    case KIND.UNION:
      base = node.variants.length
        ? `z.union([${node.variants.map((variant) => zodFor(variant, ref, indent)).join(", ")}])`
        : "z.never()";
      break;
    case KIND.INTERSECTION:
      base = node.parts.length
        ? node.parts.map((part) => zodFor(part, ref, indent)).reduce((left, right) => `z.intersection(${left}, ${right})`)
        : "z.unknown()";
      break;
    case KIND.ARRAY: {
      const inner = zodFor(node.items, ref, indent);
      const chains = [];
      if (node.minItems !== undefined) chains.push(`.min(${node.minItems})`);
      if (node.maxItems !== undefined) chains.push(`.max(${node.maxItems})`);
      base = `z.array(${inner})${chains.join("")}`;
      break;
    }
    case KIND.OBJECT:
      base = objectSchema(node, ref, indent);
      break;
    default:
      base = "z.unknown()";
  }
  if (node.nullable && node.kind !== KIND.NULL) base += ".nullable()";
  return base;
}

export function emitZod(ir) {
  const emitted = new Set();
  const stack = new Set();
  const lines = [
    `// Generated by TypeForge from ${ir.rootName}.`,
    "// `z.infer` types are exported alongside each schema.",
    'import { z } from "zod";',
    "",
  ];

  const ref = (node) => {
    const name = `${pascal(node.name)}Schema`;
    if (stack.has(node.name) || !emitted.has(node.name)) return `z.lazy(() => ${name})`;
    return name;
  };

  for (const definition of orderedDefinitions(ir)) {
    const name = pascal(definition.name);
    stack.add(definition.name);
    if (definition.node.description) lines.push(...lineComments(definition.node.description));
    lines.push(`export const ${name}Schema = ${zodFor(definition.node, ref, "")};`);
    lines.push(`export type ${name} = z.infer<typeof ${name}Schema>;`, "");
    stack.delete(definition.name);
    emitted.add(definition.name);
  }

  const rootName = pascal(ir.rootName);
  if (ir.root.kind === KIND.REF && pascal(ir.root.name) === rootName) {
    // The root is the named schema; nothing extra to emit.
  } else if (ir.root.kind === KIND.REF) {
    lines.push(`export const ${rootName}Schema = ${pascal(ir.root.name)}Schema;`);
    lines.push(`export type ${rootName} = z.infer<typeof ${rootName}Schema>;`);
  } else {
    lines.push(`export const ${rootName}Schema = ${zodFor(ir.root, ref, "")};`);
    lines.push(`export type ${rootName} = z.infer<typeof ${rootName}Schema>;`);
  }
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}
